/**
 * Build `client.echarts.js` — the lazy chunk that carries ECharts.
 *
 * DSH's Client ModuleLoader serves any sibling file named `client.<name>.js`
 * from the plugin route, and a bundle pulls it in with
 * `require.async('./client.echarts.js')`. That is how a plain-JS plugin ships a
 * real charting library with no bundler.
 *
 * The wrapper is the same one every shipped DSH client bundle uses: declare
 * `module` and `exports` in the factory scope, and ECharts' UMD preamble takes
 * its first branch (`e(exports)`) instead of falling through to the
 * `globalThis.echarts = {}` arm. The library is handed to us; no global leaks.
 *
 * Run: node build-echarts.mjs
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const echartsDir = join(here, 'node_modules', 'echarts')
const source = join(echartsDir, 'dist', 'echarts.min.js')
const target = join(here, 'client.echarts.js')

const version = JSON.parse(readFileSync(join(echartsDir, 'package.json'), 'utf8')).version
const umd = readFileSync(source, 'utf8')

// The chunk's module id is `<owner package>/<file name>` — the loader keys a
// chunk by exactly that pair, so this string is load-bearing.
const chunkId = 'dsh-smart-ui/client.echarts.js'

const output = [
  `// Generated by build-echarts.mjs from echarts@${version} — do not edit.`,
  '// Apache ECharts is licensed under the Apache License 2.0; see node_modules/echarts/licenses.',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(chunkId)},`,
  '  factory(require) {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  umd,
  '    return module.exports;',
  '  },',
  '})',
  '',
].join('\n')

writeFileSync(target, output, 'utf8')
console.log(`wrote ${target} (${Math.round(statSync(target).size / 1024)} KB) from echarts@${version}`)
