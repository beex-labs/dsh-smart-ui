/**
 * Build `client.engine.js` — the lazy chunk that carries the shared engine.
 *
 * `engine.cjs` is the single source of truth for the component registry, the
 * safe expression language, spec validation, action planning and the streaming
 * protocol. The Host imports it as CommonJS; the Client loads this generated
 * wrapper through `require.async('./client.engine.js')`. Same file, same
 * behaviour on both sides.
 *
 * Run: node build-engine.mjs
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const source = readFileSync(join(here, 'engine.cjs'), 'utf8')
const target = join(here, 'client.engine.js')

// The chunk's module id is `<owner package>/<file name>` — the loader keys a
// chunk by exactly that pair, so this string is load-bearing.
const chunkId = 'dsh-intelligent-ui/client.engine.js'

const output = [
  '// Generated by build-engine.mjs from engine.cjs — do not edit.',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(chunkId)},`,
  '  factory(require) {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  source,
  '    return module.exports;',
  '  },',
  '})',
  '',
].join('\n')

writeFileSync(target, output, 'utf8')
console.log(`wrote ${target} (${Math.round(statSync(target).size / 1024)} KB) from engine.cjs`)
