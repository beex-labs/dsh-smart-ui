/**
 * Build `client.mermaid.js` — the lazy chunk that carries Mermaid.
 *
 * Mermaid is the right renderer for flowcharts, UML (class / sequence / state /
 * ER), mind maps and the rest of the diagram family: it has real orthogonal
 * routing, UML semantics and dedicated layout engines. ECharts' `graph` series
 * is a relationship-network renderer and was the wrong tool for those.
 *
 * `dist/mermaid.min.js` is a single self-contained IIFE (zero dynamic imports,
 * no sibling chunks), which is exactly what the plugin route can serve: any
 * file named `client.<name>.js` next to `client.js`.
 *
 * The stock file ends with `globalThis["mermaid"] = ...`, which would leak a
 * global and give our factory nothing. We let it assign, capture the value, and
 * delete the global again, so the chunk behaves like a normal module.
 *
 * Run: node build-mermaid.mjs
 */
import { readFileSync, writeFileSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const dir = join(here, 'node_modules', 'mermaid')
const source = join(dir, 'dist', 'mermaid.min.js')
const target = join(here, 'client.mermaid.js')

const version = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).version
let iife = readFileSync(source, 'utf8')

// The stock bundle ends with
//   globalThis["mermaid"] = globalThis.__esbuild_esm_mermaid_nm["mermaid"].default;
// At script scope `var __esbuild_esm_mermaid_nm` becomes a global, so that
// lookup works. Inside our factory the declaration is function-scoped, so the
// global lookup is undefined and the line throws. Point it at the local.
const TAIL = 'globalThis["mermaid"] = globalThis.__esbuild_esm_mermaid_nm["mermaid"].default;'
if (!iife.includes(TAIL)) {
  throw new Error('mermaid build: expected trailing global assignment not found — check the dist file')
}
iife = iife.replace(TAIL, 'globalThis["mermaid"] = __esbuild_esm_mermaid_nm["mermaid"].default;')

const chunkId = 'dsh-smart-ui/client.mermaid.js'

const output = [
  `// Generated by build-mermaid.mjs from mermaid@${version} — do not edit.`,
  '// Mermaid is licensed under the MIT License; see node_modules/mermaid/LICENSE.',
  'window.__ModuleLoader__.load({',
  `  id: ${JSON.stringify(chunkId)},`,
  '  factory(require) {',
  '    var module = { exports: {} };',
  '    var exports = module.exports;',
  '    // The bundle assigns to globalThis.mermaid; capture and remove it so the',
  '    // chunk leaves no trace on the page and still returns the API.',
  '    var hadGlobal = Object.prototype.hasOwnProperty.call(globalThis, "mermaid");',
  '    var priorGlobal = globalThis.mermaid;',
  iife,
  '    var api = globalThis.mermaid;',
  '    if (hadGlobal) globalThis.mermaid = priorGlobal; else delete globalThis.mermaid;',
  '    return api;',
  '  },',
  '})',
  '',
].join('\n')

writeFileSync(target, output, 'utf8')
console.log(`wrote ${target} (${(statSync(target).size / 1024 / 1024).toFixed(1)} MB) from mermaid@${version}`)
